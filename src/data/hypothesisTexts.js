export function otherInfluences({ outcomeIsTest = false, factorLabel = 'фактор' } = {}) {
  const items = [
    `Другие обстоятельства. Дни, когда ${factorLabel}, могли отличаться и чем-то ещё: другими показателями из дневника, нагрузкой, днём недели, самочувствием, событиями. Возможно, дело в них.`,
    'Совпадение — не причина. Даже если показатели меняются вместе, это не значит, что одно влияет на другое: оба могут зависеть от чего-то третьего, или связь может идти в обратную сторону.',
    'Регрессия к среднему. После особенно плохого (или хорошего) дня следующий почти всегда ближе к обычному — сам по себе, без всякой причины (Barnett и др., 2005).',
    'Мало данных. Несколько дней — это немного; результат на других днях может оказаться другим.',
    'Самоотчёт. Оценки в дневнике субъективны: на них может влиять настроение и ожидания — например, если вы знаете свою гипотезу.',
  ];
  if (outcomeIsTest) {
    items.splice(2, 0, 'Эффект практики. Время реакции может улучшаться просто потому, что вы привыкаете к тесту. Тренировочные сеансы исключены, но привыкание может продолжаться и позже (Scharfen и др., 2018). Также на результат влияют старание и время суток.');
  }
  return items;
}

